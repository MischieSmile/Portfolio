const nameElement = document.querySelector('#name');
const namePosition = document.querySelector('.name-position');
const details = document.querySelector('.identity-details');
const cue = document.querySelector('.scroll-cue');
const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
let motionEnabled = !reducedMotion.matches;
let geometry;
let docked = scrollY > 24;
let nameProgress = docked ? 1 : 0;
let frame = 0;
let transitionStart = null;
let transitionFrom = nameProgress;

const clamp = value => Math.min(1, Math.max(0, value));
const smoothstep = value => value * value * (3 - 2 * value);

function measureName() {
  // Measure the real text and preserve its document slot before making it fixed.
  nameElement.classList.remove('floating');
  nameElement.style.transform = '';
  nameElement.style.opacity = '';
  namePosition.style.width = '';
  namePosition.style.height = '';
  const rect = nameElement.getBoundingClientRect();
  namePosition.style.width = `${rect.width}px`;
  namePosition.style.height = `${rect.height}px`;
  const fontSize = parseFloat(getComputedStyle(nameElement).fontSize);
  const mobile = innerWidth <= 700;
  geometry = {
    x: rect.left,
    y: rect.top + scrollY,
    targetX: mobile ? 24 : Math.max(40, (innerWidth - 1180) / 2),
    targetY: mobile ? 28 : 36,
    scale: (mobile ? 25 : 31) / fontSize
  };
  nameElement.classList.add('floating');
  renderMotion();
}

function renderMotion() {
  if (!geometry) return;
  // Scrolling triggers a complete transition, rather than scrubbing its timeline.
  const progress = nameProgress;
  const x = geometry.x + (geometry.targetX - geometry.x) * progress;
  const y = geometry.y + (geometry.targetY - geometry.y) * progress;
  const scale = 1 + (geometry.scale - 1) * progress;
  nameElement.style.transform = `translate3d(${x}px, ${y}px, 0) scale(${scale})`;
  // Fade in a quiet background only once the name is close to its resting position.
  document.documentElement.style.setProperty('--name-dock', String(smoothstep(clamp((progress - .65) / .35))));
  details.style.opacity = String(1 - smoothstep(clamp(progress * 2)));
  details.style.transform = `translate3d(0, ${progress * 32}px, 0)`;
  cue.style.opacity = String(1 - clamp(progress * 3));
}

function animate(time) {
  if (transitionStart === null) transitionStart = time;
  const elapsed = clamp((time - transitionStart) / (motionEnabled ? 650 : 220));
  const eased = 1 - Math.pow(1 - elapsed, 3);
  nameProgress = transitionFrom + ((docked ? 1 : 0) - transitionFrom) * eased;
  renderMotion();
  if (elapsed < 1) frame = requestAnimationFrame(animate);
  else { frame = 0; transitionStart = null; }
}

window.addEventListener('scroll', () => {
  // Different thresholds avoid toggling back and forth near the top.
  const nextDocked = docked ? scrollY > 8 : scrollY > 24;
  if (nextDocked === docked) return;
  docked = nextDocked;
  transitionFrom = nameProgress;
  transitionStart = null;
  if (!frame) frame = requestAnimationFrame(animate);
}, { passive: true });
window.addEventListener('resize', measureName);
function applyMotionPreference() {
  document.documentElement.classList.toggle('motion-enabled', motionEnabled);
  document.documentElement.classList.toggle('motion-reduced', !motionEnabled);
}

reducedMotion.addEventListener('change', () => {
  motionEnabled = !reducedMotion.matches;
  applyMotionPreference();
  measureName();
});

function initialLanguage() {
  try {
    const saved = localStorage.getItem('portfolio-language');
    if (saved === 'en' || saved === 'tr') return saved;
  } catch {}
  try { if (Intl.DateTimeFormat().resolvedOptions().timeZone === 'Europe/Istanbul') return 'tr'; } catch {}
  return (navigator.languages?.[0] || navigator.language || 'en').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

function setLanguage(next, remember = false) {
  const language = next === 'tr' ? 'tr' : 'en';
  document.documentElement.lang = language;
  document.title = language === 'tr' ? 'Baha Taşkın — Yazılım Geliştirici' : 'Baha Taşkın — Software Developer';
  document.querySelector('meta[name="description"]').content = language === 'tr' ? 'Bir yazılım geliştiricinin seçili projeleri, deneyimleri ve geçmişi.' : 'Selected projects, experience, and background of a software developer.';
  document.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = translations[language][element.dataset.i18n]; });
  document.querySelectorAll('[data-lang]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.lang === language)));
  document.querySelector('.language-switch').setAttribute('aria-label', language === 'tr' ? 'Dil seçimi' : 'Language');
  document.querySelector('.socials').setAttribute('aria-label', language === 'tr' ? 'Sosyal medya ve iletişim' : 'Social and contact links');
  cue.setAttribute('aria-label', language === 'tr' ? 'Hakkımda bölümüne git' : 'Scroll to About');
  if (remember) { try { localStorage.setItem('portfolio-language', language); } catch {} }
  applyMotionPreference();
  measureName();
}

document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang, true)));
details.addEventListener('focusin', () => {
  if (motionEnabled && scrollY > 100) window.scrollTo({ top: 0, behavior: 'instant' });
});
setLanguage(initialLanguage());
document.documentElement.classList.add('enter');
nameElement.addEventListener('animationend', event => {
  if (event.target.classList.contains('name-last')) document.documentElement.classList.remove('enter');
});
if (document.fonts) document.fonts.ready.then(measureName);
